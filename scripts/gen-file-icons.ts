// bun scripts/gen-file-icons.ts — copies Zeron's Symbols file-icon set (refs/zeron, from miguelsolorio/vscode-symbols)
// into web/file-icons and writes what fileicons.ts resolves through: a lean manifest (names and extensions to icons)
// and an index of every icon as a file the UI loads when it's first needed.
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const from = join(root, "refs/zeron/crates/ui");
const to = join(root, "web/file-icons");
if (!existsSync(from)) throw new Error(`no Zeron checkout at ${from}`);

rmSync(to, { recursive: true, force: true });
mkdirSync(to, { recursive: true });
for (const dir of ["files", "folders"]) cpSync(join(from, "assets/file-icons", dir), join(to, dir), { recursive: true });
cpSync(join(from, "assets/file-icons/LICENSE.symbols"), join(to, "LICENSE.symbols"));

const upstream = await Bun.file(join(from, "src/file-icons.json")).json();
// Two ids the upstream manifest uses without defining them; its language associations show what they mean.
const ALIAS: Record<string, string> = { less: "brackets-sky", yml: "yaml" };
const asset = (id: string): string | null => {
  const path: string | undefined = upstream.iconDefinitions[ALIAS[id] ?? id]?.iconPath;
  return path?.replace(/^\.\/icons\//, "").replace(/\.svg$/, "") ?? null;
};
const table = (entries: Record<string, string>) => {
  const out: Record<string, string> = {};
  for (const [name, id] of Object.entries(entries)) {
    const a = asset(id);
    if (a) out[name.toLowerCase()] = a;
  }
  return out;
};
const manifest = {
  file: asset(upstream.file) ?? "files/document",
  folder: asset(upstream.folder) ?? "folders/folder",
  fileNames: table(upstream.fileNames),
  fileExtensions: table(upstream.fileExtensions),
  folderNames: table(upstream.folderNames),
};
writeFileSync(join(to, "manifest.json"), JSON.stringify(manifest));

const keys = ["files", "folders"].flatMap((dir) => readdirSync(join(to, dir)).filter((f) => f.endsWith(".svg")).map((f) => `${dir}/${f.slice(0, -4)}`)).sort();
const lines = [
  "// Generated by scripts/gen-file-icons.ts: every Symbols icon as a file of the build, by its key.",
  ...keys.map((k, i) => `import i${i} from "./${k}.svg" with { type: "file" };`),
  "",
  "export const ICON_URLS: Record<string, string> = {",
  ...keys.map((k, i) => `  ${JSON.stringify(k)}: i${i},`),
  "};",
  "",
];
writeFileSync(join(to, "index.ts"), lines.join("\n"));
console.log(`${keys.length} icons, ${Object.keys(manifest.fileNames).length} names, ${Object.keys(manifest.fileExtensions).length} extensions, ${Object.keys(manifest.folderNames).length} folder names`);
