export type IconName = keyof typeof ICONS;

/** `<span class="icon">` holding the glyph; size it with CSS (or `px`). `filled` paints the outline solid. */
/** Each icon's markup parsed once; an icon drawn is a copy of it (lists draw thousands). */
const parsed = new Map<IconName, HTMLSpanElement>();

export function icon(name: IconName, px?: number, cls = "", filled = false): HTMLSpanElement {
  let model = parsed.get(name);
  if (!model) {
    model = document.createElement("span");
    model.innerHTML = ICONS[name];
    parsed.set(name, model);
  }
  const span = model.cloneNode(true) as HTMLSpanElement;
  span.className = `icon ${cls}${filled ? " filled" : ""}`.trim();
  if (px) span.style.width = span.style.height = `${px}px`;
  return span;
}

/** A harness's brand mark: OpenAI's and Cursor's tinted by the surface, Claude's kept in its orange (as Zeron does). */
const BRAND: Record<HarnessId, IconName> = { codex: "openai", claude: "claude", cursor: "cursor" };
export const harnessIcon = (harness: HarnessId, px?: number, cls = "") => icon(BRAND[harness], px, `${cls} brand-${harness}`.trim());

